// Generates ENDPOINTS.md from the `docs` exported by every route module.
import { writeFile } from 'node:fs/promises';
import { modules } from '../src/app.js';

let md = '# Endpoint Reference\n\n> Auto-generated by `npm run docs`. Live list: `GET /`.\n\n';
let total = 0;
for (const [section, m] of modules) {
  md += `## ${section}\n\n| Method | Path | What it demonstrates | Theory |\n|---|---|---|---|\n`;
  for (const [method, path, description, topic] of m.docs) {
    const [file, q] = topic.split(' Q');
    md += `| ${method} | \`${path}\` | ${description} | [${file.split('/')[0]}${q ? ' Q' + q : ''}](../${file}) |\n`;
    total++;
  }
  md += '\n';
}
md += `**Total: ${total} endpoints** (plus \`GET /\` index).\n`;
await writeFile(new URL('../ENDPOINTS.md', import.meta.url), md);
console.log(`ENDPOINTS.md written (${total} endpoints)`);
process.exit(0);
